#!/usr/bin/env python3
"""Assemble M3ParkStub.S into M3ParkStub.h (docs/WIN11-BIGCORES.md stage B2).

  gen-m3park-stub.py [--check]

clang -target aarch64-none-elf assembles the stub; its .text is taken from the ELF object and
checked: no relocations (position independent), 4-byte aligned, the eight 8-byte literals at the
end. The header holds the bytes and the literals' offset, with the disassembly as a comment for
review. --check: fail if the committed header differs.
"""
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'M3ParkStub.S')
OUT = os.path.join(HERE, 'M3ParkStub.h')
LIT_SIZE = 64


def elf_sections(elf):
    assert elf[:4] == b'\x7fELF' and elf[4] == 2 and elf[5] == 1, 'not ELF64 LE'
    shoff, = struct.unpack_from('<Q', elf, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', elf, 0x3A)
    secs = []
    for i in range(shnum):
        name, typ, flags, addr, off, size = struct.unpack_from('<IIQQQQ', elf, shoff + i * shentsize)
        secs.append((name, typ, off, size))
    stroff = secs[shstrndx][2]
    out = {}
    for name, typ, off, size in secs:
        n = elf[stroff + name:elf.index(b'\0', stroff + name)].decode()
        out[n] = (typ, elf[off:off + size])
    return out


def build():
    with tempfile.TemporaryDirectory() as td:
        obj = os.path.join(td, 'stub.o')
        subprocess.run(['clang', '-target', 'aarch64-none-elf', '-c', SRC, '-o', obj], check=True)
        secs = elf_sections(open(obj, 'rb').read())
        dis = subprocess.run(['xcrun', 'llvm-objdump', '-d', '--no-show-raw-insn', obj],
                             capture_output=True, text=True).stdout
    assert not any(n.startswith('.rela') for n in secs), 'the stub has relocations'
    text = secs['.text'][1]
    assert len(text) % 8 == 0 and len(text) <= 0x7F8 - LIT_SIZE, len(text)
    assert text[-LIT_SIZE:] == b'\0' * LIT_SIZE, 'literals not at the end'
    lines = [ln.strip() for ln in dis.splitlines() if ln.strip().split(':')[0].strip().isalnum() and '\t' in ln]
    body = ',\n'.join('  ' + ', '.join(f'0x{b:02x}' for b in text[i:i + 12]) for i in range(0, len(text), 12))
    return (f"""/** @file
  M3ParkStub.h: GENERATED by gen-m3park-stub.py from M3ParkStub.S; do not edit.

  Copyright (c) 2026, Starbite. SPDX-License-Identifier: GPL-2.0-only
**/

#ifndef M3_PARK_STUB_H_
#define M3_PARK_STUB_H_

//
// {len(text)} bytes; literals (mailbox, UID, then the digits of el, frq, kctl, spin, wake, t;
// 8 bytes each) at offset
// M3_PARK_STUB_LIT. Disassembly (clang):
""" + ''.join(f'//   {ln}\n' for ln in lines) + f"""//
#define M3_PARK_STUB_LIT  {len(text) - LIT_SIZE}u

STATIC CONST UINT8  mM3ParkStub[{len(text)}] = {{
{body}
}};

#endif
""")


def main():
    h = build()
    if '--check' in sys.argv[1:]:
        if not os.path.exists(OUT) or open(OUT).read() != h:
            sys.exit('stale (run gen-m3park-stub.py): ' + OUT)
        print('M3ParkStub.h up to date')
        return
    open(OUT, 'w').write(h)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
