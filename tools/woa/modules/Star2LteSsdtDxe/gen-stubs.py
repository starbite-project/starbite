#!/usr/bin/env python3
"""Assemble the M3 stubs into C headers (docs/WIN11-BIGCORES.md stages B2, B3a).

  gen-stubs.py [--check]

For each stub (STUBS: name, literal bytes) clang -target aarch64-none-elf assembles <name>.S; its
.text is taken from the ELF object and checked: no relocations (position independent), 8-byte
size, the literals (zero) at the end. <name>.h holds the bytes as m<name>[] and the literals'
offset as <NAME>_LIT, with the disassembly as a comment for review. --check: fail if a committed
header differs.
"""
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
STUBS = [('M3ParkStub', 64, 'M3_PARK_STUB_LIT',
          'literals (mailbox, UID, then the digits of el, frq, kctl, spin, wake, t; 8 bytes each)'),
         ('M3RunStub', 8, 'M3_RUN_STUB_LIT', 'literal (the context address, 8 bytes)'),
         ('M3BootStub', 8, 'M3_BOOT_STUB_LIT', 'literal (the context address, 8 bytes)')]


def elf_sections(elf):
    assert elf[:4] == b'\x7fELF' and elf[4] == 2 and elf[5] == 1, 'not ELF64 LE'
    shoff, = struct.unpack_from('<Q', elf, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', elf, 0x3A)
    secs = []
    for i in range(shnum):
        name, typ, flags, addr, off, size = struct.unpack_from('<IIQQQQ', elf, shoff + i * shentsize)
        secs.append((name, typ, off, size))
    stroff = secs[shstrndx][2]
    out = {}
    for name, typ, off, size in secs:
        n = elf[stroff + name:elf.index(b'\0', stroff + name)].decode()
        out[n] = (typ, elf[off:off + size])
    # symbols: name -> value (offset in .text)
    syms = {}
    if '.symtab' in out and '.strtab' in out:
        st, strs = out['.symtab'][1], out['.strtab'][1]
        for i in range(0, len(st), 24):
            nm, info, other, shndx, value, size = struct.unpack_from('<IBBHQQ', st, i)
            if nm:
                syms[strs[nm:strs.index(b'\0', nm)].decode()] = value
    out['__syms__'] = (0, syms)
    return out


def build(name, LIT_SIZE, litname, litdesc):
    SRC = os.path.join(HERE, name + '.S')
    with tempfile.TemporaryDirectory() as td:
        obj = os.path.join(td, 'stub.o')
        subprocess.run(['clang', '-target', 'aarch64-none-elf', '-c', SRC, '-o', obj], check=True)
        secs = elf_sections(open(obj, 'rb').read())
        dis = subprocess.run(['xcrun', 'llvm-objdump', '-d', '--no-show-raw-insn', obj],
                             capture_output=True, text=True).stdout
    assert not any(n.startswith('.rela') for n in secs), 'the stub has relocations'
    entry = secs['__syms__'][1][name[0].lower() + name[1:3].lower() + name[3:].replace('Stub', '').lower() + '_stub']
    text = secs['.text'][1]
    assert len(text) % 8 == 0 and len(text) <= 0xFF0, len(text)
    assert text[-LIT_SIZE:] == b'\0' * LIT_SIZE, 'literals not at the end'
    lines = [ln.strip() for ln in dis.splitlines() if ln.strip().split(':')[0].strip().isalnum() and '\t' in ln]
    packed = []                          # a run of padding nops as one line
    for ln in lines:
        if ln.endswith('nop'):
            if packed and packed[-1].endswith('nop (padding)'):
                continue
            ln = ln.split(':')[0] + ': ... nop (padding)'
        packed.append(ln)
    lines = packed
    body = ',\n'.join('  ' + ', '.join(f'0x{b:02x}' for b in text[i:i + 12]) for i in range(0, len(text), 12))
    return (f"""/** @file
  {name}.h: GENERATED by gen-stubs.py from {name}.S; do not edit.

  Copyright (c) 2026, Starbite. SPDX-License-Identifier: GPL-2.0-only
**/

#ifndef {litname[:-4]}_H_
#define {litname[:-4]}_H_

//
// {len(text)} bytes; {litdesc} at offset
// {litname}. Disassembly (clang):
""" + ''.join(f'//   {ln}\n' for ln in lines) + f"""//
#define {litname}  {len(text) - LIT_SIZE}u
#define {litname[:-4]}_ENTRY  {entry}u

STATIC CONST UINT8  m{name}[{len(text)}] = {{
{body}
}};

#endif
""")


def main():
    for name, lit, litname, litdesc in STUBS:
        out = os.path.join(HERE, name + '.h')
        h = build(name, lit, litname, litdesc)
        if '--check' in sys.argv[1:]:
            if not os.path.exists(out) or open(out).read() != h:
                sys.exit('stale (run gen-stubs.py): ' + out)
            print(name + '.h up to date')
            continue
        open(out, 'w').write(h)
        print('wrote', out)


if __name__ == '__main__':
    main()
