#!/usr/bin/env python3
"""Generate 0024-starbite-usb-host-dxe.patch (docs/WIN11-USB.md section 6).

  tools/woa/patches/gen-0024.py [--check]

Sources of truth: tools/woa/modules/Star2LteUsbHostDxe/ and starbite/s9usb/. This script
  1. compiles UsbHostSsdt.asl with iasl in the lima VM "starbite" and writes UsbHostSsdtAml.h
     (a C array; edk2's own AmlToC rule writes into the source tree, which the VM sees read-only),
  2. writes the patch: the module + a copy of starbite/s9usb as new files under
     Platform/Star2LtePkg/Drivers/Star2LteUsbHostDxe/, and the DSC/FDF lines, both under
     "!ifdef STAR2LTE_USB_HOST_DXE" so builds without that define are unchanged.
The DSC/FDF hunks use context lines that none of patches 0001-0023 change (the UFS/SCSI lines in
the DSC, the EnglishDxe/Fat/TODO lines in the FDF), so 0024 applies to any subset of them.
--check: regenerate in memory and fail if the committed files differ.
"""
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
MOD = os.path.join(ROOT, 'tools/woa/modules/Star2LteUsbHostDxe')
S9 = os.path.join(ROOT, 'starbite/s9usb')
PATCH = os.path.join(ROOT, 'tools/woa/patches/0024-starbite-usb-host-dxe.patch')
AMLH = os.path.join(MOD, 'UsbHostSsdtAml.h')
DEST = 'Platform/Star2LtePkg/Drivers/Star2LteUsbHostDxe'


def compile_asl():
    src = open(os.path.join(MOD, 'UsbHostSsdt.asl'), 'rb').read()
    cmd = ('set -e; d=$(mktemp -d); cd "$d"; cat > UsbHostSsdt.asl; '
           'iasl -p UsbHostSsdt UsbHostSsdt.asl >iasl.log 2>&1 || { cat iasl.log >&2; exit 1; }; '
           'cat UsbHostSsdt.aml; rm -rf "$d"')
    aml = subprocess.run(['limactl', 'shell', 'starbite', '--', 'bash', '-c', cmd], input=src,
                         stdout=subprocess.PIPE, check=True).stdout
    assert aml[:4] == b'SSDT', 'iasl output is not an SSDT'
    assert int.from_bytes(aml[4:8], 'little') == len(aml), 'SSDT length mismatch'
    assert sum(aml) & 0xFF == 0, 'SSDT checksum'
    assert aml[10:16] == b'STRBTE' and aml[16:24] == b'STRBUSBH', 'SSDT OEM ids'
    return aml


def aml_header(aml):
    out = ['/** @file',
           '  UsbHostSsdt.asl compiled by iasl (generated by tools/woa/patches/gen-0024.py; do not edit).',
           '',
           '  Copyright (c) 2026, Starbite. SPDX-License-Identifier: GPL-2.0-only',
           '**/',
           '',
           '#ifndef USB_HOST_SSDT_AML_H_',
           '#define USB_HOST_SSDT_AML_H_',
           '',
           f'// {len(aml)} bytes, OEM STRBTE/STRBUSBH',
           'STATIC UINT8  UsbHostSsdtAml[] = {']
    for i in range(0, len(aml), 12):
        out.append('  ' + ', '.join(f'0x{b:02X}' for b in aml[i:i + 12]) + ',')
    out += ['};', '', '#endif', '']
    return '\n'.join(out)


def new_file(path, text):
    lines = text.splitlines()
    assert text.endswith('\n'), path
    return [f'--- /dev/null', f'+++ b/{path}', f'@@ -0,0 +1,{len(lines)} @@'] + ['+' + ln for ln in lines]


def insert_between(path, line, before, added, after):
    """`added` between the `before` and `after` context lines; `line` = the first context line's
    number in the unpatched file (patch finds it at an offset when earlier patches moved it)."""
    n = len(before) + len(after)
    return ([f'--- a/{path}', f'+++ b/{path}', f'@@ -{line},{n} +{line},{n + len(added)} @@'] +
            [' ' + ln for ln in before] + ['+' + ln for ln in added] + [' ' + ln for ln in after])


def build_patch(amlh):
    out = ['starbite: Star2LteUsbHostDxe, the DWC3 as a USB host for Windows (docs/WIN11-USB.md).',
           'Generated by tools/woa/patches/gen-0024.py from tools/woa/modules/Star2LteUsbHostDxe and',
           'starbite/s9usb. Only built with -D STAR2LTE_USB_HOST_DXE -D STARBITE_USBH_VBUS=<0|1>.',
           '']
    for name in sorted(os.listdir(MOD)):
        if name.startswith('.'):
            continue
        text = amlh if name == 'UsbHostSsdtAml.h' else open(os.path.join(MOD, name)).read()
        out += new_file(f'{DEST}/{name}', text)
    for name in sorted(os.listdir(S9)):
        p = os.path.join(S9, name)
        if os.path.isfile(p) and name.endswith(('.c', '.h')):
            out += new_file(f'{DEST}/s9usb/{name}', open(p).read())
    out += insert_between('Platform/Star2LtePkg/Star2LtePkg.dsc', 392, [
        '  Platform/Star2LtePkg/Drivers/Star2LteUfsHcDxe/Star2LteUfsHcDxe.inf',
        '  MdeModulePkg/Bus/Ufs/UfsPassThruDxe/UfsPassThruDxe.inf',
    ], [
        '!ifdef STAR2LTE_USB_HOST_DXE',
        f'  {DEST}/Star2LteUsbHostDxe.inf {{',
        '    <BuildOptions>',
        '      *_*_*_CC_FLAGS = -DSTARBITE_USBH_VBUS=$(STARBITE_USBH_VBUS)',
        '  }',
        '!endif',
    ], ['  MdeModulePkg/Bus/Scsi/ScsiBusDxe/ScsiBusDxe.inf',
        '  MdeModulePkg/Bus/Scsi/ScsiDiskDxe/ScsiDiskDxe.inf'])
    out += insert_between('Platform/Star2LtePkg/Star2LtePkg.fdf', 163, [
        '  INF MdeModulePkg/Universal/Disk/UnicodeCollation/EnglishDxe/EnglishDxe.inf',
        '  INF FatPkg/EnhancedFatDxe/Fat.inf',
    ], [
        '!ifdef STAR2LTE_USB_HOST_DXE',
        f'  INF {DEST}/Star2LteUsbHostDxe.inf',
        '!endif',
    ], ['  # TODO: USB stack for HID/keyboard + install media:',
        '  # INF MdeModulePkg/Bus/Pci/XhciDxe/XhciDxe.inf'])
    return '\n'.join(out) + '\n'


def main():
    check = '--check' in sys.argv[1:]
    amlh = aml_header(compile_asl())
    if not check:
        open(AMLH, 'w').write(amlh)
    patch = build_patch(amlh)
    if check:
        bad = [p for p, want in ((AMLH, amlh), (PATCH, patch))
               if not os.path.exists(p) or open(p).read() != want]
        if bad:
            sys.exit('stale (run tools/woa/patches/gen-0024.py): ' + ', '.join(os.path.relpath(b, ROOT) for b in bad))
        print('0024 up to date')
        return
    open(PATCH, 'w').write(patch)
    print(f'wrote {os.path.relpath(AMLH, ROOT)} and {os.path.relpath(PATCH, ROOT)}')


if __name__ == '__main__':
    main()
