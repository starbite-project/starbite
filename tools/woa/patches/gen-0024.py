#!/usr/bin/env python3
"""Generate 0024-starbite-usb-ssdt-dxe.patch (docs/WIN11-USB.md section 6).

  tools/woa/patches/gen-0024.py [--check]

Sources of truth: tools/woa/modules/Star2LteUsbDxe/, tools/woa/modules/Star2LteSsdtDxe/ and
starbite/s9usb/. The patch adds both modules (the USB one with a copy of starbite/s9usb, both with
tools/woa/modules/common/StarbiteLog.h) as new
files under Platform/Star2LtePkg/Drivers/, and their DSC/FDF lines under
"!ifdef STAR2LTE_USB_DXE" / "!ifdef STAR2LTE_SSDT_DXE", so builds without those defines are
unchanged. The SSDT blobs are not part of it: tools/woa/acpi/*.asl -> iasl -> tools/woa/ssdt-ffs.py
(build-win-usbhost.sh).
The DSC/FDF hunks use context lines that none of patches 0001-0023 change (the UFS/SCSI lines in
the DSC, the EnglishDxe/Fat/TODO lines in the FDF), so 0024 applies to any subset of them.
--check: regenerate in memory and fail if the committed patch differs.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
MODS = os.path.join(ROOT, 'tools/woa/modules')
S9 = os.path.join(ROOT, 'starbite/s9usb')
PATCH = os.path.join(ROOT, 'tools/woa/patches/0024-starbite-usb-ssdt-dxe.patch')
DRV = 'Platform/Star2LtePkg/Drivers'
USB = f'{DRV}/Star2LteUsbDxe'
SSDT = f'{DRV}/Star2LteSsdtDxe'


def new_file(path, text):
    lines = text.splitlines()
    assert text.endswith('\n'), path
    return ['--- /dev/null', f'+++ b/{path}', f'@@ -0,0 +1,{len(lines)} @@'] + ['+' + ln for ln in lines]


def insert_between(path, line, before, added, after):
    """`added` between the `before` and `after` context lines; `line` = the first context line's
    number in the unpatched file (patch finds it at an offset when earlier patches moved it)."""
    n = len(before) + len(after)
    return ([f'--- a/{path}', f'+++ b/{path}', f'@@ -{line},{n} +{line},{n + len(added)} @@'] +
            [' ' + ln for ln in before] + ['+' + ln for ln in added] + [' ' + ln for ln in after])


def files_of(directory, dest, suffixes=None):
    out = []
    for name in sorted(os.listdir(directory)):
        p = os.path.join(directory, name)
        if name.startswith('.') or not os.path.isfile(p):
            continue
        if suffixes and not name.endswith(suffixes):
            continue
        out += new_file(f'{dest}/{name}', open(p).read())
    return out


def build_patch():
    out = ['starbite: Star2LteUsbDxe (the DWC3 in the boot role for Windows) and Star2LteSsdtDxe (installs the',
           'Starbite SSDT blobs during dispatch; with STARBITE_PPTT_FIX=1 the PPTT first gets the CPU caches);',
           'docs/WIN11-USB.md. Generated by tools/woa/patches/gen-0024.py. Built only with -D STAR2LTE_USB_DXE',
           '(+ STARBITE_USB_ROLE/ACPI/VBUS) and/or -D STAR2LTE_SSDT_DXE (+ STARBITE_PPTT_FIX).',
           '']
    out += files_of(os.path.join(MODS, 'Star2LteUsbDxe'), USB)
    out += files_of(os.path.join(MODS, 'common'), USB)
    out += files_of(S9, f'{USB}/s9usb', ('.c', '.h'))
    out += files_of(os.path.join(MODS, 'Star2LteSsdtDxe'), SSDT, ('.c', '.h', '.inf'))   # not the stub's .S/generator
    out += files_of(os.path.join(MODS, 'common'), SSDT)
    out += insert_between('Platform/Star2LtePkg/Star2LtePkg.dsc', 392, [
        '  Platform/Star2LtePkg/Drivers/Star2LteUfsHcDxe/Star2LteUfsHcDxe.inf',
        '  MdeModulePkg/Bus/Ufs/UfsPassThruDxe/UfsPassThruDxe.inf',
    ], [
        '!ifdef STAR2LTE_USB_DXE',
        f'  {USB}/Star2LteUsbDxe.inf {{',
        '    <BuildOptions>',
        '      *_*_*_CC_FLAGS = -DSTARBITE_USB_ROLE=$(STARBITE_USB_ROLE) -DSTARBITE_USB_ACPI=$(STARBITE_USB_ACPI) -DSTARBITE_USB_VBUS=$(STARBITE_USB_VBUS)',
        '  }',
        '!endif',
        '!ifdef STAR2LTE_SSDT_DXE',
        f'  {SSDT}/Star2LteSsdtDxe.inf {{',
        '    <BuildOptions>',
        '      *_*_*_CC_FLAGS = -DSTARBITE_PPTT_FIX=$(STARBITE_PPTT_FIX) -DSTARBITE_M3_PROBE=$(STARBITE_M3_PROBE) -DSTARBITE_M3_PARK=$(STARBITE_M3_PARK) -DSTARBITE_M3_RUN=$(STARBITE_M3_RUN) -DSTARBITE_M3_BOOT=$(STARBITE_M3_BOOT) -DSTARBITE_CORES8=$(STARBITE_CORES8) -DSTARBITE_M3_PSCIEMU=$(STARBITE_M3_PSCIEMU)',
        '  }',
        '!endif',
    ], ['  MdeModulePkg/Bus/Scsi/ScsiBusDxe/ScsiBusDxe.inf',
        '  MdeModulePkg/Bus/Scsi/ScsiDiskDxe/ScsiDiskDxe.inf'])
    out += insert_between('Platform/Star2LtePkg/Star2LtePkg.fdf', 163, [
        '  INF MdeModulePkg/Universal/Disk/UnicodeCollation/EnglishDxe/EnglishDxe.inf',
        '  INF FatPkg/EnhancedFatDxe/Fat.inf',
    ], [
        '!ifdef STAR2LTE_USB_DXE',
        f'  INF {USB}/Star2LteUsbDxe.inf',
        '!endif',
        '!ifdef STAR2LTE_SSDT_DXE',
        f'  INF {SSDT}/Star2LteSsdtDxe.inf',
        '!endif',
    ], ['  # TODO: USB stack for HID/keyboard + install media:',
        '  # INF MdeModulePkg/Bus/Pci/XhciDxe/XhciDxe.inf'])
    return '\n'.join(out) + '\n'


def main():
    patch = build_patch()
    if '--check' in sys.argv[1:]:
        if not os.path.exists(PATCH) or open(PATCH).read() != patch:
            sys.exit('stale (run tools/woa/patches/gen-0024.py): ' + os.path.relpath(PATCH, ROOT))
        print('0024 up to date')
        return
    open(PATCH, 'w').write(patch)
    print(f'wrote {os.path.relpath(PATCH, ROOT)}')


if __name__ == '__main__':
    main()
