#!/usr/bin/env python3
"""Plan an on-device redeploy of WINESP/WINDOWS from the VHDX on the phone's SD card.

  redeploy-from-sd.py SPARSE_HEADER_COPY GPT_PRIMARY OUT.sh

SPARSE_HEADER_COPY is a local sparse file holding only the VHDX headers, region
table, metadata and BAT pulled from the card (same offsets). The output is a
shell script for TWRP: it checks the card file's sha256, then for every 32 MiB
VHDX block covering a partition either copies it from the card with dd or
zero-fills it, and verifies each copied range on the device (sha256 of the card
range vs the partition range). Everything is MiB-aligned.
"""
import struct
import sys

sys.path.insert(0, __file__.rsplit('/', 1)[0])
from vhdx import Vhdx, FULLY_PRESENT  # noqa: E402

MiB = 1 << 20
CARD = '/external_sd/starbite-win.vhdx'


def parts(gpt):
    b = open(gpt, 'rb').read()
    S = 4096
    p = {}
    for i in range(128):
        e = b[2 * S + i * 128:2 * S + (i + 1) * 128]
        first, last = struct.unpack('<QQ', e[32:48])
        p[e[56:128].decode('utf-16le').rstrip('\0')] = (first * S, (last - first + 1) * S)
    return p


def main():
    v = Vhdx(sys.argv[1])
    p = parts(sys.argv[2])
    states = {}
    for i in range((v.size + v.block - 1) // v.block):
        st = v.entry(i)[0]
        states[st] = states.get(st, 0) + 1
    assert set(states) <= {0, 1, 2, 3, FULLY_PRESENT}, f'partially present blocks: {states}'
    sha = open('build/woa/starbite-win.vhdx.sha256').read().split()[0]
    out = ['#!/sbin/sh', '# generated by tools/woa/redeploy-from-sd.py', 'set -u', f'C={CARD}',
           'L=/tmp/redeploy.log', ': > $L', 'grep -qE "sda2[67] " /proc/mounts && { echo MOUNTED >> $L; exit 1; }',
           'echo "card sha256..." >> $L',
           f'[ "$(sha256sum $C | cut -c1-64)" = "{sha}" ] || {{ echo CARD_SHA_MISMATCH >> $L; exit 1; }}',
           'echo "card ok" >> $L', 'bad=0']
    total_copy = total_zero = 0
    for name, n in (('WINESP', 26), ('WINDOWS', 27)):
        poff, plen = p[name]
        assert poff % MiB == 0 and plen % MiB == 0
        pos = poff
        while pos < poff + plen:
            i, within = divmod(pos, v.block)
            k = min(v.block - within, poff + plen - pos)
            st, foff = v.entry(i)
            rel = pos - poff
            assert within % MiB == 0 and k % MiB == 0 and rel % MiB == 0
            if st == FULLY_PRESENT:
                src = foff + within
                out.append(f'dd if=$C of=/dev/block/sda{n} bs=1048576 skip={src // MiB} seek={rel // MiB} '
                           f'count={k // MiB} conv=notrunc 2>/dev/null')
                out.append(f'a=$(dd if=$C bs=1048576 skip={src // MiB} count={k // MiB} 2>/dev/null | sha256sum | cut -c1-64); '
                           f'b=$(dd if=/dev/block/sda{n} bs=1048576 skip={rel // MiB} count={k // MiB} 2>/dev/null | sha256sum | cut -c1-64); '
                           f'[ "$a" = "$b" ] || {{ bad=$((bad+1)); echo "MISMATCH sda{n} +{rel // MiB}" >> $L; }}')
                total_copy += k
            else:
                out.append(f'dd if=/dev/zero of=/dev/block/sda{n} bs=1048576 seek={rel // MiB} count={k // MiB} '
                           f'conv=notrunc 2>/dev/null')
                total_zero += k
            out.append(f'echo "sda{n} +{(rel + k) // MiB}/{plen // MiB} MiB" >> $L')
            pos += k
    out += ['sync', 'echo "DONE bad=$bad" >> $L']
    open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
    print(f'block states {states}; copy {total_copy // MiB} MiB, zero {total_zero // MiB} MiB; '
          f'{len(out)} lines -> {sys.argv[3]}')


if __name__ == '__main__':
    main()
