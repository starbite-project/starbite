#!/usr/bin/env python3
"""Make shim/starlte/post_logo.h: the Starbite "One mark" logo for the loader's POST screen.

The POST screen (shim/starlte/post.c) shows only the Starbite logo with a small animation. It
draws the approved splash, "One mark" (docs/concepts/splash/HANDOFF.md), at exactly the place
S-Boot draws logo.jpg (its 1079 x 1747 box at panel (180, 1144)), so that

  - with One mark in UP_PARAM the POST screen is S-Boot's splash, pixel for pixel, plus the
    animation, and
  - menu v7's intro (intro7_capture) finds the same two bands it finds in S-Boot's One mark
    splash when POST leaves the logo on the panel.

Input: the splash's source PNG (build/splash-concepts/final/logo.png, the file logo.jpg is
encoded from). Two parts are kept:

  word  the white "starbite" (rows below 1300): grey, so one coverage byte per pixel (A8)
  star  the blue star (rows above 1300): R, G, B per pixel (premultiplied over black)

Both are PackBits-compressed (c < 128: c + 1 literal bytes follow; c >= 128: the next byte
c - 127 times). The header has no pointers (the loader Image must have no absolute
relocations). Usage:

  build/venv/bin/python -I tools/brand/post-logo.py build/splash-concepts/final/logo.png \
      shim/starlte/post_logo.h
"""
import hashlib
import sys
from pathlib import Path

from PIL import Image

BOX_X, BOX_Y = 180, 1144          # where S-Boot draws logo.jpg (1:1)
SPLIT_Y = 1300                    # panel row between the star and the word


def packbits(data):
    out = bytearray()
    i, n = 0, len(data)
    while i < n:
        j = i
        while j < n and j - i < 128 and data[j] == data[i]:
            j += 1
        if j - i >= 3:
            out += bytes([127 + (j - i), data[i]])      # a run of 3..128
            i = j
            continue
        k = i
        lit = bytearray()
        while k < n and len(lit) < 128:
            r = k
            while r < n and r - k < 3 and data[r] == data[k]:
                r += 1
            if r - k >= 3:
                break
            lit.append(data[k])
            k += 1
        out += bytes([len(lit) - 1]) + lit
        i = k
    return bytes(out)


def unpack(data, size):
    out = bytearray()
    i = 0
    while i < len(data):
        c = data[i]
        i += 1
        if c < 128:
            out += data[i:i + c + 1]
            i += c + 1
        else:
            out += bytes([data[i]]) * (c - 127)
            i += 1
    assert len(out) == size, (len(out), size)
    return bytes(out)


def bbox(px, w, h, upper):
    x0 = y0 = 1 << 30
    x1 = y1 = -1
    for y in range(h):
        if (y + BOX_Y < SPLIT_Y) != upper:
            continue
        for x in range(w):
            if max(px[x, y]):
                x0, y0, x1, y1 = min(x0, x), min(y0, y), max(x1, x), max(y1, y)
    return x0, y0, x1 + 1, y1 + 1


def carray(name, data):
    lines = [f'static const uint8_t {name}[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    raw = src.read_bytes()
    im = Image.open(src).convert('RGB')
    w, h = im.size
    if (w, h) != (1079, 1747):
        sys.exit(f'{src}: {w} x {h}, want the 1079 x 1747 splash box')
    px = im.load()
    star = bbox(px, w, h, True)
    word = bbox(px, w, h, False)
    a8 = bytearray()
    for y in range(word[1], word[3]):
        for x in range(word[0], word[2]):
            r, g, b = px[x, y]
            if not r == g == b:
                sys.exit(f'word pixel ({x}, {y}) is not grey: {r, g, b}')
            a8.append(r)
    rgb = bytearray()
    sx = sy = sa = 0
    for y in range(star[1], star[3]):
        for x in range(star[0], star[2]):
            r, g, b = px[x, y]
            if max(r, g, b) != b:
                sys.exit(f'star pixel ({x}, {y}) is not blue-led: {r, g, b}')
            rgb += bytes((r, g, b))
            sx += b * x
            sy += b * y
            sa += b
    pw, ps = packbits(bytes(a8)), packbits(bytes(rgb))
    assert unpack(pw, len(a8)) == bytes(a8) and unpack(ps, len(rgb)) == bytes(rgb)
    cx = BOX_X + sx / sa + 0.5          # pixel centres
    cy = BOX_Y + sy / sa + 0.5
    out = f'''/* SPDX-License-Identifier: GPL-2.0-only
 * GENERATED by tools/brand/post-logo.py from the One mark splash source
 * ({src.name}, sha256 {hashlib.sha256(raw).hexdigest()[:16]}...); do not edit.
 * Panel coordinates (S-Boot draws logo.jpg at ({BOX_X}, {BOX_Y})). PackBits: c < 128: c + 1 literal
 * bytes follow; c >= 128: the next byte c - 127 times.
 *   word: the white "starbite", one coverage byte per pixel
 *   star: the blue star, R G B per pixel (premultiplied over black; its alpha is B / 255)
 */
#pragma once
#include <stdint.h>

#define PL_WORD_X {BOX_X + word[0]}
#define PL_WORD_Y {BOX_Y + word[1]}
#define PL_WORD_W {word[2] - word[0]}
#define PL_WORD_H {word[3] - word[1]}
#define PL_STAR_X {BOX_X + star[0]}
#define PL_STAR_Y {BOX_Y + star[1]}
#define PL_STAR_W {star[2] - star[0]}
#define PL_STAR_H {star[3] - star[1]}
/* the star's centre (its alpha centroid), in 1/16 px */
#define PL_STAR_CX16 {round(cx * 16)}
#define PL_STAR_CY16 {round(cy * 16)}

{carray('pl_word', pw)}

{carray('pl_star', ps)}
'''
    dst.write_text(out)
    print(f'{dst}: word {word[2] - word[0]} x {word[3] - word[1]} at ({BOX_X + word[0]}, {BOX_Y + word[1]}) '
          f'{len(a8)} -> {len(pw)} bytes; star {star[2] - star[0]} x {star[3] - star[1]} at '
          f'({BOX_X + star[0]}, {BOX_Y + star[1]}) {len(rgb)} -> {len(ps)} bytes; centre ({cx:.2f}, {cy:.2f})')


if __name__ == '__main__':
    main()
