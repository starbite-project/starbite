#!/usr/bin/env python3
"""Build the EngineerMode glyph atlas: "SBFONT01", appended to build/brand/menu.sbm.

    build/venv/bin/python tools/brand/em-font.py

Fonts (Holo-era Android): Roboto v2.138 (Apache 2.0, tools/brand/fonts) and the
system's Menlo for hex/log views. Codes 32..126 are ASCII; 0x80.. are extra
symbols the bootloader's strings use (shim/starlte/ui.h UI_DEG etc.).

Format (little endian):
  "SBFONT01" u32 nfonts
  per font: u32 id, size, ascent, descent, line, first, count, data_size (multiple of 4)
            count x { i16 advance, u16 w, u16 h, i16 bx, i16 by, u16 pad, u32 off }
            data_size bytes of 8-bit alpha (row-major per glyph, at off)
  by = top of the bitmap relative to the baseline (negative = above).
"""
import struct
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / 'tools/brand/fonts'
OUT = ROOT / 'build/brand'

EXTRA = ['°', '·', '…', '↑', '↓', '←', '→', 'µ', '±', '×', '■', '▲', '▼', '✓']
CODES = [chr(c) for c in range(32, 127)] + EXTRA        # 0x80 + i for EXTRA[i]

# id: (file, size)  -- sizes for the 1440 px wide panel (~3.2 px per dp)
SPEC = {
    0: (FONTS / 'Roboto-Regular.ttf', 46),    # list primary
    1: (FONTS / 'Roboto-Regular.ttf', 36),    # secondary, values
    2: (FONTS / 'Roboto-Medium.ttf', 38),     # tabs, buttons
    3: (FONTS / 'Roboto-Regular.ttf', 58),    # action bar title
    4: (Path('/System/Library/Fonts/Menlo.ttc'), 30),   # mono: hex, logs
    5: (FONTS / 'Roboto-Light.ttf', 120),     # big readouts (clock, %)
    6: (FONTS / 'Roboto-Medium.ttf', 30),     # status bar
}


def build_font(fid, path, size):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in CODES:
        try:
            adv = font.getlength(ch)
            x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
        except Exception:
            adv, x0, y0, x1, y1 = size // 2, 0, 0, 0, 0
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(data)
        if w and h:
            img = Image.new('L', (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
            data += img.tobytes()
        glyphs.append((round(adv), w, h, x0, y0, off))
    line = round((ascent + descent) * 1.18)
    while len(data) % 4:                       # keep the next font's header word-aligned
        data += b'\0'
    hdr = struct.pack('<8I', fid, size, ascent, descent, line, 32, len(CODES), len(data))
    tbl = b''.join(struct.pack('<hHHhhHI', a, w, h, bx, by, 0, off) for a, w, h, bx, by, off in glyphs)
    return hdr + tbl + bytes(data)


def main():
    blob = bytearray(b'SBFONT01' + struct.pack('<I', len(SPEC)))
    for fid, (path, size) in SPEC.items():
        blob += build_font(fid, path, size)
    while len(blob) % 4:
        blob += b'\0'
    (OUT / 'emfont.bin').write_bytes(blob)
    menu = (OUT / 'menu.sbm').read_bytes()
    (OUT / 'menu-em.sbm').write_bytes(menu + blob)
    print(f'build/brand/emfont.bin: {len(SPEC)} fonts, {len(blob)} bytes; '
          f'menu-em.sbm = menu.sbm + atlas = {len(menu) + len(blob)} bytes')
    # C header with the extra symbol codes, so strings can use them.
    hdr = ['/* Generated by tools/brand/em-font.py: extra glyph codes (atlas order). */', '#pragma once']
    names = ['DEG', 'DOT', 'ELLIPSIS', 'UP', 'DOWN', 'LEFT', 'RIGHT', 'MICRO', 'PLUSMINUS', 'TIMES',
             'SQUARE', 'TRI_UP', 'TRI_DOWN', 'CHECK']
    for i, n in enumerate(names):
        hdr.append(f'#define UI_{n} "\\x{0x80 + i:02x}"')
    (ROOT / 'shim/starlte/ui_glyphs.h').write_text('\n'.join(hdr) + '\n')


if __name__ == '__main__':
    sys.exit(main())
