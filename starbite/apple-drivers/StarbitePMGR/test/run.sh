#!/bin/sh
# Host tests of StarbitePMGR's hw/ plus the M2 bring-up simulation (mock EL3 firmware, mock PMU, and the GIC-400
# model from ../../StarbiteGICv2/test). The CPU table comes from tools/board/starlte.board. Run: sh test/run.sh
set -eu
cd "$(dirname "$0")"
root=$(cd ../../../.. && pwd)
gen=${TMPDIR:-/tmp}/sb-pmgr-test.$$
mkdir -p "$gen"
trap 'rm -rf "$gen"' EXIT
python3 -I - "$root/tools/board/starlte.board" "$gen/board_cpus.h" <<'PY'
import sys, tomllib
b = tomllib.loads(open(sys.argv[1]).read())
kinds = {c['id']: c['kind'] for c in b['cluster']}
cpus = sorted(b['cpu'], key=lambda c: c['logical'])
p = b['psci']
assert p['method'] == 'smc', p['method']
with open(sys.argv[2], 'w') as f:
    f.write('/* generated by test/run.sh from tools/board/starlte.board */\n')
    f.write('static const struct { unsigned logical; unsigned long long mpidr, psci; unsigned cluster; char kind; }\n')
    f.write('BOARD_CPUS[] = {\n')
    for c in cpus:
        f.write(f"\t{{ {c['logical']}, {c['mpidr']:#x}ull, {c['psci']:#x}ull, {c['cluster']}, '{kinds[c['cluster']]}' }},\n")
    f.write('};\n#define BOARD_NCPUS (sizeof(BOARD_CPUS) / sizeof(BOARD_CPUS[0]))\n')
    f.write(f"#define BOARD_PSCI_CPU_ON {p['cpu_on']:#x}u\n#define BOARD_PSCI_CPU_OFF {p['cpu_off']:#x}u\n")
    f.write(f"#define BOARD_PSCI_CPU_SUSPEND {p['cpu_suspend']:#x}u\n")
PY
gic=../../StarbiteGICv2
cc -std=c11 -Wall -Wextra -Werror -O1 -g -fsanitize=address,undefined -I "$gen" \
    -o "$gen/test" test_pmgr.c ../hw/sb_smp.c ../hw/sb_psci.c "$gic/test/mock_gic.c" "$gic/hw/sb_gicv2.c"
"$gen/test"
