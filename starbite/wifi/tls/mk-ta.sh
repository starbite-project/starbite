#!/bin/sh
# tls/ta.c: the trust anchors (CA roots) sbhttp checks servers against, from Mozilla's CA bundle as curl
# publishes it (https://curl.se/ca/cacert.pem, checked against its .sha256), converted by BearSSL's own
# `brssl ta` (built from build/bearssl-src, the pinned commit in tls/bearssl/README.starbite).
#   sh starbite/wifi/tls/mk-ta.sh [cacert.pem]      (default: build/cacert/cacert.pem, fetched if missing)
# Re-run it to refresh the roots (CAs come and go: Mozilla's list changes a few times a year).
set -eu
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
build="$root/build"
for b in "$root/build" "$root/../../../build"; do [ -d "$b/bearssl-src" ] && { build=$b; break; }; done
pem=${1:-"$build/cacert/cacert.pem"}
if [ ! -f "$pem" ]; then
    mkdir -p "$(dirname "$pem")"
    curl -sS -o "$pem" https://curl.se/ca/cacert.pem
    curl -sS -o "$pem.sha256" https://curl.se/ca/cacert.pem.sha256
    want=$(cut -d' ' -f1 "$pem.sha256")
    got=$(shasum -a 256 "$pem" 2>/dev/null | cut -d' ' -f1 || sha256sum "$pem" | cut -d' ' -f1)
    [ "$want" = "$got" ] || { echo "mk-ta: cacert.pem does not match its .sha256" >&2; exit 1; }
fi
brssl="$build/bearssl-src/build/brssl"
if [ ! -x "$brssl" ]; then
    echo "mk-ta: build brssl first: make -C $build/bearssl-src (the commit in tls/bearssl/README.starbite)" >&2
    exit 1
fi
date=$(sed -n 's/^## Certificate data from Mozilla as of: //p' "$pem" | head -1)
sum=$(shasum -a 256 "$pem" 2>/dev/null | cut -d' ' -f1 || sha256sum "$pem" | cut -d' ' -f1)
n=$(grep -c 'BEGIN CERTIFICATE' "$pem")
{
    echo "/* SPDX-License-Identifier: MPL-2.0"
    echo " * The CA roots sbhttp trusts (generated by tls/mk-ta.sh; do not edit): $n certificates from Mozilla's"
    echo " * CA bundle (curl's cacert.pem, \"Certificate data from Mozilla as of: $date\","
    echo " * sha256 $sum), converted by BearSSL's brssl ta. */"
    echo '#include "bearssl.h"'
    echo '#include "../http.h"'
    "$brssl" ta "$pem" 2>/dev/null |
        sed -e 's/^static const br_x509_trust_anchor TAs\[\([0-9]*\)\]/const br_x509_trust_anchor sbtls_tas[\1]/' \
            -e 's/^#define TAs_NUM *\([0-9]*\)/const unsigned sbtls_tas_num = \1;/'
} > "$here/ta.c"
echo "mk-ta: $here/ta.c: $n roots (Mozilla, $date)"
