#!/bin/sh
# tls/tls_chains.c: two real certificate chains as servers sent them (an RSA one and an ECDSA one), with the time
# they were fetched, for the offline TLS self-check (sbtls_selftest in http.c's callers: the chains must be
# accepted by BearSSL's X.509 engine against tls/ta.c at that time, and refused a year later). Public data only.
#   sh starbite/wifi/tls/mk-selftest.sh
set -eu
here=$(cd "$(dirname "$0")" && pwd)
now=$(date -u +%s)
tmp=$(mktemp -d "${TMPDIR:-/tmp}/sbtls.XXXXXX")
# $3: openssl options (the RSA chain is asked for with RSA-only TLS 1.2 ciphers: example.com has both kinds)
fetch() {
    # shellcheck disable=SC2086
    echo | openssl s_client $3 -connect "$1:443" -servername "$1" -showcerts 2>/dev/null |
        awk -v out="$tmp/$2-" '/BEGIN CERT/{n++; on=1} on{print > (out n ".pem")} /END CERT/{on=0}'
}
fetch example.com rsa "-tls1_2 -cipher ECDHE-RSA-AES128-GCM-SHA256"
fetch valid-isrgrootx2.letsencrypt.org ec ""
for k in rsa ec; do
    want=$([ $k = rsa ] && echo rsaEncryption || echo id-ecPublicKey)
    openssl x509 -in "$tmp/$k-1.pem" -noout -text | grep -q "Public Key Algorithm: $want" ||
        { echo "mk-selftest: the $k chain's leaf is not $want" >&2; exit 1; }
done
python3 - "$tmp" "$now" > "$here/tls_chains.c" <<'PY'
import glob, os, subprocess, sys
tmp, now = sys.argv[1], int(sys.argv[2])
print("/* SPDX-License-Identifier: MIT")
print(" * Generated by tls/mk-selftest.sh (do not edit): two certificate chains as their servers sent them, fetched at")
print(" * %d (UTC seconds), for the offline TLS self-check. Public certificates only. */" % now)
print('#include "tls_check.h"')
for kind, host in (("rsa", "example.com"), ("ec", "valid-isrgrootx2.letsencrypt.org")):
    files = sorted(glob.glob(os.path.join(tmp, kind + "-*.pem")), key=lambda p: int(p.rsplit("-", 1)[1].split(".")[0]))
    names = []
    for i, f in enumerate(files):
        der = subprocess.run(["openssl", "x509", "-in", f, "-outform", "DER"], capture_output=True, check=True).stdout
        n = "st_%s_%d" % (kind, i)
        names.append((n, len(der)))
        print("static const unsigned char %s[%d] = {" % (n, len(der)))
        for k in range(0, len(der), 16):
            print("    " + ", ".join("0x%02x" % b for b in der[k:k + 16]) + ",")
        print("};")
    print("static const struct sbtls_cert st_%s[] = { %s };" % (kind, ", ".join("{ %s, %d }" % x for x in names)))
print("const struct sbtls_chain sbtls_selftest_chains[2] = {")
print('    { "example.com", st_rsa, sizeof(st_rsa) / sizeof(st_rsa[0]), 0 },')
print('    { "valid-isrgrootx2.letsencrypt.org", st_ec, sizeof(st_ec) / sizeof(st_ec[0]), 1 },')
print("};")
print("const uint64_t sbtls_selftest_time = %dull;" % now)
PY
n=$(grep -c 'static const unsigned char' "$here/tls_chains.c")
echo "mk-selftest: $here/tls_chains.c: $n certificates, fetched at $now"
