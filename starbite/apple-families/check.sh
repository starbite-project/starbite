# Compile-check every file in starbite/apple-families/<Family>/SOURCES.txt against our xnu-12377 STARLTE kernel
# with tools/apple/kcheck.py (the kernel's own flags for a built-in IOKit .cpp / BSD .c, -fsyntax-only; nothing is
# written to the build tree).
#   sh starbite/apple-families/stage.sh <Family> && sh starbite/apple-families/check.sh <Family> [-v]
#
# SOURCES.txt: one source per line, path relative to the clone (build/families/<Family>) or "_gen/..." (iig output),
# optionally followed by flags for that file; a line "@cflags FLAGS" gives flags for every file. Flags are the ones
# the kernel build must add (<obj>_CFLAGS_ADD): -include FILE (relative to starbite/apple-families), -DNAME[=V],
# -UNAME. kcheck.py only takes -I, so each source is checked through a generated wrapper
# (build/families/_gen/<Family>/wrap/<file>) that applies the flags as #include / #define / #undef and then
# #includes the real source by absolute path (its own quoted includes still resolve next to it).
# Include paths: the staged header layout (build/families/_inc/<Family>), the clone's source folders, the iig
# output. Prints one line per file and "N of M OK"; the full log is build/families/_gen/<Family>.check.log.
set -u
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
HERE=$ROOT/starbite/apple-families
fam=$1; verbose=${2:-}
FAM=$ROOT/build/families
S=$FAM/$fam
LIST=$HERE/$fam/SOURCES.txt
WRAP=$FAM/_gen/$fam/wrap
rm -rf "$WRAP"; mkdir -p "$WRAP"
INC="-I $FAM/_inc/$fam -I $S"
case $fam in
IOHIDFamily) INC="$INC -I $S/IOHIDFamily -I $S/IOHIDFamily/IOHIDEventDummyService -I $S/IOHIDSystem -I $S/IOHIDSystem/IOKit/hidsystem -I $S/IOHIDSystem/IOHIDDescriptorParser -I $FAM/_inc/$fam/IOKit/hid -I $FAM/_gen/IOHIDFamily" ;;
IOStorageFamily) INC="$INC -I $FAM/_gen/IOStorageFamily" ;;
# <net/classq/classq.h> (via <net/dlil.h>) is a Kernel.framework PrivateHeaders file that XNU does not export to
# its own build; our tree's bsd/ is searched last for it
IONetworkingFamily) INC="$INC -I $ROOT/build/dxb-12377/xnu/bsd" ;;
esac
COMMON=$(sed -n 's/^@cflags[[:space:]]*//p' "$LIST")

emit_flags() { # flags...
	while [ $# -gt 0 ]; do
		case $1 in
		-include) echo "#include \"$HERE/$2\""; shift ;;
		-D*) d=${1#-D}; case $d in *=*) echo "#define ${d%%=*} ${d#*=}" ;; *) echo "#define $d 1" ;; esac ;;
		-U*) echo "#undef ${1#-U}" ;;
		*) echo "#error unknown flag $1" ;;
		esac
		shift
	done
}

sed -e 's/#.*//' -e '/^@cflags/d' -e '/^[[:space:]]*$/d' "$LIST" | while read -r f defs; do
	case $f in /*) p=$f ;; _gen/*) p=$FAM/$f ;; *) p=$S/$f ;; esac
	w=$WRAP/$(basename "$p")
	{
		echo "/* generated by starbite/apple-families/check.sh for $f */"
		# shellcheck disable=SC2086
		emit_flags $COMMON $defs
		echo "#include \"$p\""
	} > "$w"
	out=$(python3 "$ROOT/tools/apple/kcheck.py" "$w" $INC 2>&1)
	rc=$?
	if [ -n "$verbose" ]; then echo "$out"; else echo "$out" | head -1; fi
	echo "RESULT $rc"
done > "$FAM/_gen/$fam.check.log" 2>&1
grep -v '^RESULT ' "$FAM/_gen/$fam.check.log"
n=$(grep -c '^RESULT ' "$FAM/_gen/$fam.check.log")
ok=$(grep -c '^RESULT 0$' "$FAM/_gen/$fam.check.log")
echo "$fam: $ok of $n OK"
[ "$ok" -eq "$n" ]
