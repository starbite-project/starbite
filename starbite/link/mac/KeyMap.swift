// Starbite Link, Mac viewer: macOS virtual key codes (kVK_*, physical positions) to USB HID usages.
// SBLINK sends keys by HID position (PROTOCOL.md INPUT_KEY); the Windows keyboard layout picks the character.

import Carbon.HIToolbox

enum KeyMap {
    /// HID usage page 0x07 (keyboard) usage for a kVK_* code, or nil.
    static let keyboard: [UInt16: UInt16] = [
        0x00: 0x04, 0x01: 0x16, 0x02: 0x07, 0x03: 0x09, 0x04: 0x0B, 0x05: 0x0A, 0x06: 0x1D, 0x07: 0x1B,  // A S D F H G Z X
        0x08: 0x06, 0x09: 0x19, 0x0A: 0x64, 0x0B: 0x05, 0x0C: 0x14, 0x0D: 0x1A, 0x0E: 0x08, 0x0F: 0x15,  // C V §(ISO) B Q W E R
        0x10: 0x1C, 0x11: 0x17, 0x12: 0x1E, 0x13: 0x1F, 0x14: 0x20, 0x15: 0x21, 0x16: 0x23, 0x17: 0x22,  // Y T 1 2 3 4 6 5
        0x18: 0x2E, 0x19: 0x26, 0x1A: 0x24, 0x1B: 0x2D, 0x1C: 0x25, 0x1D: 0x27, 0x1E: 0x30, 0x1F: 0x12,  // = 9 7 - 8 0 ] O
        0x20: 0x18, 0x21: 0x2F, 0x22: 0x0C, 0x23: 0x13, 0x24: 0x28, 0x25: 0x0F, 0x26: 0x0D, 0x27: 0x34,  // U [ I P Return L J '
        0x28: 0x0E, 0x29: 0x33, 0x2A: 0x31, 0x2B: 0x36, 0x2C: 0x38, 0x2D: 0x11, 0x2E: 0x10, 0x2F: 0x37,  // K ; \ , / N M .
        0x30: 0x2B, 0x31: 0x2C, 0x32: 0x35, 0x33: 0x2A, 0x35: 0x29,                                      // Tab Space ` Backspace Esc
        0x36: 0xE7, 0x37: 0xE3, 0x38: 0xE1, 0x39: 0x39, 0x3A: 0xE2, 0x3B: 0xE0, 0x3C: 0xE5, 0x3D: 0xE6,  // RCmd Cmd Shift Caps Opt Ctrl RShift ROpt
        0x3E: 0xE4,                                                                                      // RCtrl
        0x40: 0x6C, 0x41: 0x63, 0x43: 0x55, 0x45: 0x57, 0x47: 0x53, 0x4B: 0x54, 0x4C: 0x58, 0x4E: 0x56,  // F17 KP. KP* KP+ Clear KP/ KPEnter KP-
        0x4F: 0x6D, 0x50: 0x6E, 0x51: 0x67, 0x52: 0x62, 0x53: 0x59, 0x54: 0x5A, 0x55: 0x5B, 0x56: 0x5C,  // F18 F19 KP= KP0..KP4
        0x57: 0x5D, 0x58: 0x5E, 0x59: 0x5F, 0x5A: 0x6F, 0x5B: 0x60, 0x5C: 0x61,                          // KP5 KP6 KP7 F20 KP8 KP9
        0x5D: 0x89, 0x5E: 0x87, 0x5F: 0x85,                                                              // JIS Yen, _, KP,
        0x60: 0x3E, 0x61: 0x3F, 0x62: 0x40, 0x63: 0x3C, 0x64: 0x41, 0x65: 0x42, 0x66: 0x91, 0x67: 0x44,  // F5 F6 F7 F3 F8 F9 Eisu F11
        0x68: 0x90, 0x69: 0x68, 0x6A: 0x6B, 0x6B: 0x69, 0x6D: 0x43, 0x6E: 0x65, 0x6F: 0x45, 0x71: 0x6A,  // Kana F13 F16 F14 F10 Menu F12 F15
        0x72: 0x49, 0x73: 0x4A, 0x74: 0x4B, 0x75: 0x4C, 0x76: 0x3D, 0x77: 0x4D, 0x78: 0x3B, 0x79: 0x4E,  // Help=Insert Home PgUp Del F4 End F2 PgDn
        0x7A: 0x3A, 0x7B: 0x50, 0x7C: 0x4F, 0x7D: 0x51, 0x7E: 0x52,                                      // F1 Left Right Down Up
    ]

    /// Consumer page (0x0C) usages for the Mac's volume keys when they arrive as key codes.
    static let consumer: [UInt16: UInt16] = [0x48: 0xE9, 0x49: 0xEA, 0x4A: 0xE2]

    /// On ISO keyboards macOS reports the key left of 1 and the key right of left Shift swapped
    /// relative to their HID positions.
    static let isISO: Bool = KBGetLayoutType(Int16(LMGetKbdType())) == kKeyboardISO

    /// (page, usage) for a key code. cmdAsCtrl swaps Cmd and Ctrl (Cmd = Ctrl, Ctrl = Windows key).
    static func hid(_ keyCode: UInt16, cmdAsCtrl: Bool) -> (UInt16, UInt16)? {
        var code = keyCode
        if isISO {
            if code == 0x0A { code = 0x32 } else if code == 0x32 { code = 0x0A }
        }
        if let u = consumer[code] { return (0x0C, u) }
        guard var u = keyboard[code] else { return nil }
        if cmdAsCtrl {
            switch u {
            case 0xE3: u = 0xE0
            case 0xE7: u = 0xE4
            case 0xE0: u = 0xE3
            case 0xE4: u = 0xE7
            default: break
            }
        }
        return (0x07, u)
    }

    /// The NX_DEVICE* bit (device-dependent modifier flag) for a modifier key code, and the class flag.
    static func modifierBits(_ keyCode: UInt16) -> (device: UInt, flag: NSEventModifierFlagsRaw)? {
        switch keyCode {
        case 0x3B: return (0x0001, .control)   // left Ctrl
        case 0x38: return (0x0002, .shift)     // left Shift
        case 0x3C: return (0x0004, .shift)     // right Shift
        case 0x37: return (0x0008, .command)   // left Cmd
        case 0x36: return (0x0010, .command)   // right Cmd
        case 0x3A: return (0x0020, .option)    // left Option
        case 0x3D: return (0x0040, .option)    // right Option
        case 0x3E: return (0x2000, .control)   // right Ctrl
        default: return nil
        }
    }
}

/// The device-independent modifier classes (subset of NSEvent.ModifierFlags, kept AppKit-free here).
enum NSEventModifierFlagsRaw: UInt {
    case shift = 0x20000, control = 0x40000, option = 0x80000, command = 0x100000
}
